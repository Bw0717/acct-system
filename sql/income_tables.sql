	"ACTUAL_AMOUNT" NUMBER NOT NULL ENABLE,
	"UNCOLLECTED_AMOUNT" NUMBER NOT NULL ENABLE,
	"COLLECTION_METHOD" VARCHAR2(50) COLLATE "USING_NLS_COMP",
	"COLLECTION_STATUS" CHAR(1) COLLATE "USING_NLS_COMP" DEFAULT 'N' NOT NULL ENABLE,
	"COST_AMOUNT" NUMBER,
	"ESTIMATED_PROFIT" NUMBER,
	"REMARK" VARCHAR2(500) COLLATE "USING_NLS_COMP",
	"CREATE_USER" VARCHAR2(50) COLLATE "USING_NLS_COMP",
	"CREATE_TIME" DATE DEFAULT NULL,
	"MOTIFER" VARCHAR2(50) COLLATE "USING_NLS_COMP",
	"MOTIFY_TIME" DATE,
