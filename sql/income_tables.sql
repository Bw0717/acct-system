-- ============================================================================
-- 4. 欄位說明
-- ============================================================================
/*
INC_INCOME_MAIN (收入記帳主表)
├─ SID: 系統唯一識別碼（主鍵）
├─ INCOME_ID: 收入紀錄編號（唯一值）
├─ BILL_DATE: 日期
├─ INVOICE_NO: 憑據（發票/收據號碼）
├─ CUSTOMER_NAME: 客戶名稱
├─ PROJECT: 工項
├─ PERSONNEL: 施作人員
├─ LOCATION: 地點
├─ QUOTE_AMOUNT: 報價金額
├─ ACTUAL_AMOUNT: 實做金額
├─ UNCOLLECTED_AMOUNT: 未收金額
├─ COLLECTION_METHOD: 收款方式（現金/支票/轉帳等）
├─ COLLECTION_STATUS: 收款狀態（Y/N）
├─ COST_AMOUNT: 成本金額
├─ ESTIMATED_PROFIT: 預估毛利
├─ REMARK: 備註
├─ CREATE_USER: 建立使用者
├─ CREATE_TIME: 建立時間
├─ MOTIFER: 修改者
└─ MOTIFY_TIME: 修改時間

INC_INCOME_HIST (收入記帳歷史表)
└─ 同上結構，用於記錄所有歷史版本
*/
